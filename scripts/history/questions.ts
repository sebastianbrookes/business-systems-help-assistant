  texts.map((text) => ({ text, expected }));
const timed = (
  expected: Expected,
  entries: [text: string, daysAgo: number][],
): HistoryQuestion[] =>
  entries.map(([text, daysAgo]) => ({ text, expected, daysAgo }));

